#!/usr/bin/env python3
"""Synchronised ChArUco sample collector for the Thor7 eye-to-hand setup.

The collector deliberately captures a robot transform at the image timestamp.
This avoids pairing the newest image with a different, newer TF sample, which is
the failure mode of the RViz hand-eye plugin in this workspace.
"""

from __future__ import annotations

import argparse
import math
import os
import sys
import tempfile
from collections import deque
from pathlib import Path
from typing import Any, Deque, Dict, Optional, Tuple

import cv2
import numpy as np
import yaml

import rclpy
from builtin_interfaces.msg import Time as RosTime
from geometry_msgs.msg import TransformStamped
from rclpy.duration import Duration
from rclpy.executors import ExternalShutdownException
from rclpy.node import Node
from rclpy.qos import qos_profile_sensor_data
from rclpy.time import Time
from sensor_msgs.msg import CameraInfo, Image, JointState
from std_srvs.srv import Trigger
import tf2_ros


def stamp_ns(stamp: RosTime) -> int:
    return int(stamp.sec) * 1_000_000_000 + int(stamp.nanosec)


def matrix_from_transform(msg: TransformStamped) -> np.ndarray:
    """Return the ROS parent<-child homogeneous transform."""
    t = msg.transform.translation
    q = msg.transform.rotation
    qv = np.array([q.x, q.y, q.z, q.w], dtype=np.float64)
    qnorm = float(np.linalg.norm(qv))
    if not np.isfinite(qnorm) or qnorm < 1e-12:
        raise ValueError("TF contains a zero or invalid quaternion")
    x, y, z, w = qv / qnorm
    r = np.array(
        [
            [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)],
            [2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)],
            [2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)],
        ],
        dtype=np.float64,
    )
    result = np.eye(4, dtype=np.float64)
    result[:3, :3] = r
    result[:3, 3] = [t.x, t.y, t.z]
    return result


def flatten_matrix(matrix: np.ndarray) -> list[float]:
    return [float(value) for value in np.asarray(matrix, dtype=np.float64).reshape(4, 4).ravel()]


def image_to_bgr(msg: Image) -> np.ndarray:
    """Decode the color encodings published by the RealSense ROS driver.

    Keeping this small decoder local avoids the cv_bridge/NumPy ABI mismatch
    that is common when ROS Humble is used with a newer system NumPy.
    """
    encoding = msg.encoding.lower()
    channels = {"bgr8": 3, "rgb8": 3, "bgra8": 4, "rgba8": 4, "mono8": 1}.get(encoding)
    if channels is None:
        raise ValueError(f"unsupported image encoding {msg.encoding!r}; use bgr8/rgb8/mono8")
    row_bytes = int(msg.width) * channels
    if int(msg.step) < row_bytes:
        raise ValueError(f"invalid image step {msg.step} for width {msg.width}")
    raw = np.frombuffer(msg.data, dtype=np.uint8)
    required = int(msg.height) * int(msg.step)
    if raw.size < required:
        raise ValueError("image data is shorter than height*step")
    rows = raw[:required].reshape(int(msg.height), int(msg.step))[:, :row_bytes]
    image = rows.reshape(int(msg.height), int(msg.width), channels)
    if encoding == "bgr8":
        return image.copy()
    if encoding == "rgb8":
        return cv2.cvtColor(image, cv2.COLOR_RGB2BGR)
    if encoding == "bgra8":
        return cv2.cvtColor(image, cv2.COLOR_BGRA2BGR)
    if encoding == "rgba8":
        return cv2.cvtColor(image, cv2.COLOR_RGBA2BGR)
    return cv2.cvtColor(image, cv2.COLOR_GRAY2BGR)


def rotation_angle(matrix: np.ndarray) -> float:
    trace = float(np.trace(matrix[:3, :3]))
    cosine = max(-1.0, min(1.0, (trace - 1.0) * 0.5))
    return math.acos(cosine)


def make_charuco_board(squares_x: int, squares_y: int, square_size: float, marker_size: float, dictionary_name: str):
    dictionary_id = getattr(cv2.aruco, dictionary_name, None)
    if dictionary_id is None:
        raise ValueError(f"Unknown ArUco dictionary: {dictionary_name}")
    dictionary = cv2.aruco.getPredefinedDictionary(dictionary_id)
    try:
        board = cv2.aruco.CharucoBoard((squares_x, squares_y), square_size, marker_size, dictionary)
    except (AttributeError, TypeError):
        # OpenCV 4.5 exposes the older factory function.
        board = cv2.aruco.CharucoBoard_create(squares_x, squares_y, square_size, marker_size, dictionary)
    # The board in this workspace was generated by the legacy OpenCV/RViz
    # pattern.  Newer OpenCV releases default to the non-legacy corner order;
    # markers are then detected but Charuco interpolation returns zero corners.
    if hasattr(board, "setLegacyPattern"):
        board.setLegacyPattern(True)
    return board


def detect_charuco_pose(
    image: np.ndarray,
    board: Any,
    camera_matrix: np.ndarray,
    distortion: np.ndarray,
) -> Tuple[np.ndarray, int, float]:
    """Detect all visible ChArUco corners and return T_optical_target.

    The returned transform maps board coordinates into the optical frame, the
    same convention as a ROS lookupTransform(optical, handeye_target).
    """
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY) if image.ndim == 3 else image
    charuco_corners = None
    charuco_ids = None

    detector_cls = getattr(cv2.aruco, "CharucoDetector", None)
    if detector_cls is not None:
        detector = detector_cls(board)
        try:
            charuco_params = detector.getCharucoParameters()
            charuco_params.cameraMatrix = camera_matrix
            charuco_params.distCoeffs = distortion
            charuco_params.minMarkers = 2
            detector.setCharucoParameters(charuco_params)
        except (AttributeError, cv2.error):
            pass
        try:
            detector_params = detector.getDetectorParameters()
            detector_params.cornerRefinementMethod = cv2.aruco.CORNER_REFINE_SUBPIX
            detector.setDetectorParameters(detector_params)
        except (AttributeError, cv2.error):
            pass
        result = detector.detectBoard(gray)
        if len(result) >= 2:
            charuco_corners, charuco_ids = result[0], result[1]
    else:
        dictionary = board.getDictionary()
        detector_params = cv2.aruco.DetectorParameters()
        detector_params.cornerRefinementMethod = cv2.aruco.CORNER_REFINE_SUBPIX
        marker_corners, marker_ids, _ = cv2.aruco.detectMarkers(
            gray, dictionary, parameters=detector_params
        )
        if marker_ids is not None and len(marker_ids):
            _, charuco_corners, charuco_ids = cv2.aruco.interpolateCornersCharuco(
                marker_corners,
                marker_ids,
                gray,
                board,
                cameraMatrix=camera_matrix,
                distCoeffs=distortion,
            )

    if charuco_corners is None or charuco_ids is None:
        raise ValueError("no ChArUco corners detected")

    ids = np.asarray(charuco_ids, dtype=np.int32).reshape(-1)
    pixels = np.asarray(charuco_corners, dtype=np.float64).reshape(-1, 2)
    if len(ids) != len(pixels) or len(ids) < 6:
        raise ValueError(f"only {len(ids)} ChArUco corners detected; at least 6 are required")

    board_corners = np.asarray(board.getChessboardCorners(), dtype=np.float64).reshape(-1, 3)
    if np.any(ids < 0) or np.any(ids >= len(board_corners)):
        raise ValueError("ChArUco detector returned an invalid corner id")
    object_points = board_corners[ids]

    ok, rvec, tvec = cv2.solvePnP(
        object_points,
        pixels,
        camera_matrix,
        distortion,
        flags=cv2.SOLVEPNP_ITERATIVE,
    )
    if not ok:
        ok, rvec, tvec = cv2.solvePnP(
            object_points,
            pixels,
            camera_matrix,
            distortion,
            flags=cv2.SOLVEPNP_SQPNP,
        )
    if not ok:
        raise ValueError("solvePnP failed")

    if hasattr(cv2, "solvePnPRefineLM"):
        rvec, tvec = cv2.solvePnPRefineLM(
            object_points, pixels, camera_matrix, distortion, rvec, tvec
        )

    projected, _ = cv2.projectPoints(object_points, rvec, tvec, camera_matrix, distortion)
    projected = projected.reshape(-1, 2)
    rms_px = float(np.sqrt(np.mean(np.sum((projected - pixels) ** 2, axis=1))))
    if not np.isfinite(rms_px) or float(np.asarray(tvec).reshape(-1)[2]) <= 0.0:
        raise ValueError("invalid ChArUco pose or board is behind the camera")

    rotation, _ = cv2.Rodrigues(rvec)
    transform = np.eye(4, dtype=np.float64)
    transform[:3, :3] = rotation
    transform[:3, 3] = np.asarray(tvec, dtype=np.float64).reshape(3)
    return transform, int(len(ids)), rms_px


class HandeyeCollector(Node):
    def __init__(self, args: argparse.Namespace):
        super().__init__("thor7_handeye_charuco_collector")
        self.args = args
        self.tf_buffer = tf2_ros.Buffer(cache_time=Duration(seconds=30.0))
        # Use the node's main executor for TF callbacks.  A private listener
        # thread can raise ExternalShutdownException during normal shutdown
        # (and obscures the real initialization error).
        self.tf_listener = tf2_ros.TransformListener(self.tf_buffer, self, spin_thread=False)
        self.joint_history: Deque[Tuple[int, Dict[str, float]]] = deque(maxlen=5000)
        self.camera_matrix: Optional[np.ndarray] = None
        self.distortion: Optional[np.ndarray] = None
        self.optical_frame: Optional[str] = None
        self.capture_requested = False
        self.last_capture_ns = 0
        self.last_log_ns = 0

        self.output_path = Path(args.output).expanduser()
        self.image_dir = Path(args.image_dir).expanduser() if args.image_dir else self.output_path.with_suffix("").with_name(
            self.output_path.stem + "_images"
        )
        self.image_dir.mkdir(parents=True, exist_ok=True)
        self.samples: list[dict[str, Any]] = []
        if self.output_path.exists() and not args.overwrite:
            self._load_existing()
        elif args.overwrite:
            self.output_path.unlink(missing_ok=True)

        self.board = make_charuco_board(
            args.squares_x,
            args.squares_y,
            args.square_size,
            args.marker_size,
            args.dictionary,
        )

        self.create_subscription(CameraInfo, args.camera_info_topic, self.camera_info_callback, qos_profile_sensor_data)
        self.create_subscription(Image, args.image_topic, self.image_callback, qos_profile_sensor_data)
        self.create_subscription(JointState, args.joint_topic, self.joint_callback, qos_profile_sensor_data)
        self.trigger_service = self.create_service(Trigger, args.trigger_service, self.trigger_callback)

        self.get_logger().info(
            f"Ready. Stop the arm, then call: ros2 service call {args.trigger_service} "
            "std_srvs/srv/Trigger '{}'"
        )
        self.get_logger().info(
            f"image={args.image_topic} camera_info={args.camera_info_topic} "
            f"joints={args.joint_topic} base={args.base_frame} eef={args.eef_frame} "
            f"sensor={args.sensor_frame}"
        )

    def _load_existing(self) -> None:
        try:
            data = yaml.safe_load(self.output_path.read_text())
            rows = data.get("samples", []) if isinstance(data, dict) else data
            if isinstance(rows, list):
                self.samples = [row for row in rows if isinstance(row, dict)]
                self.get_logger().warn(
                    f"Loaded {len(self.samples)} existing samples from {self.output_path}"
                )
        except (OSError, yaml.YAMLError) as exc:
            raise RuntimeError(f"cannot load existing output {self.output_path}: {exc}") from exc

    def camera_info_callback(self, msg: CameraInfo) -> None:
        matrix = np.asarray(msg.k, dtype=np.float64).reshape(3, 3)
        distortion = np.asarray(msg.d, dtype=np.float64).reshape(-1, 1)
        if not np.all(np.isfinite(matrix)) or matrix[0, 0] <= 0.0 or matrix[1, 1] <= 0.0:
            self.get_logger().warn("Ignoring invalid CameraInfo")
            return
        self.camera_matrix = matrix
        self.distortion = distortion
        if msg.header.frame_id:
            self.optical_frame = msg.header.frame_id

    def joint_callback(self, msg: JointState) -> None:
        if len(msg.name) != len(msg.position):
            return
        required = {f"joint{i}" for i in range(1, 7)}
        if not required.issubset(msg.name):
            return
        values = {name: float(position) for name, position in zip(msg.name, msg.position)}
        self.joint_history.append((stamp_ns(msg.header.stamp), values))

    def trigger_callback(self, request: Trigger.Request, response: Trigger.Response) -> Trigger.Response:
        del request
        self.capture_requested = True
        response.success = True
        response.message = "capture armed; the next valid synchronized ChArUco image will be saved"
        return response

    def _nearest_joints(self, image_ns: int) -> Optional[Tuple[int, Dict[str, float]]]:
        if not self.joint_history:
            return None
        item = min(self.joint_history, key=lambda candidate: abs(candidate[0] - image_ns))
        if abs(item[0] - image_ns) > int(self.args.max_sync_ms * 1_000_000.0):
            return None
        return item

    def _lookup(self, target: str, source: str, timestamp_ns: int) -> np.ndarray:
        stamp = Time(nanoseconds=max(0, int(timestamp_ns)))
        try:
            msg = self.tf_buffer.lookup_transform(
                target,
                source,
                stamp,
                timeout=Duration(seconds=self.args.tf_timeout),
            )
        except tf2_ros.ExtrapolationException as exc:
            # RealSense and robot TF clocks can differ by a few frames.  When
            # the image is newer than the latest dynamic TF, use that latest
            # pose only if the arm is stopped and the lag is bounded.  Do not
            # hide old-data/extrapolation errors in the other direction.
            if "future" not in str(exc).lower():
                raise
            latest = self.tf_buffer.lookup_transform(
                target,
                source,
                Time(),
                timeout=Duration(seconds=self.args.tf_timeout),
            )
            latest_ns = stamp_ns(latest.header.stamp)
            lag_ms = (int(timestamp_ns) - latest_ns) / 1.0e6
            if latest_ns > 0 and lag_ms > self.args.max_tf_lag_ms:
                raise ValueError(
                    f"TF is {lag_ms:.1f} ms behind the image; stop the arm and retry "
                    f"(limit {self.args.max_tf_lag_ms:.1f} ms)"
                ) from exc
            self.get_logger().warn(
                f"TF is {lag_ms:.1f} ms behind image; using latest {source} pose "
                "because the arm must be stopped"
            )
            msg = latest
        return matrix_from_transform(msg)

    def _is_duplicate(self, base_eef: np.ndarray) -> bool:
        for sample in self.samples:
            old = np.asarray(sample["effector_wrt_world"], dtype=np.float64).reshape(4, 4)
            delta = np.linalg.inv(old) @ base_eef
            if np.linalg.norm(delta[:3, 3]) < self.args.min_motion_m and rotation_angle(delta) < math.radians(
                self.args.min_motion_deg
            ):
                return True
        return False

    def image_callback(self, msg: Image) -> None:
        if not (self.capture_requested or self.args.auto_capture):
            return
        if self.camera_matrix is None or self.distortion is None or self.optical_frame is None:
            self._throttled_warn("waiting for valid CameraInfo", msg.header.stamp)
            return

        image_ns = stamp_ns(msg.header.stamp)
        if self.args.auto_capture and image_ns - self.last_capture_ns < int(self.args.min_interval * 1e9):
            return
        # Joint states are optional diagnostics.  The calibration pose is read
        # from tf2 at the image timestamp below, so a delayed/missing
        # /joint_states message must not silently force us to pair stale data.
        joints = self._nearest_joints(image_ns)

        try:
            image = image_to_bgr(msg)
            optical_target, corner_count, rms_px = detect_charuco_pose(
                image, self.board, self.camera_matrix, self.distortion
            )
            if corner_count < self.args.min_corners or rms_px > self.args.max_reprojection_px:
                raise ValueError(
                    f"detection quality rejected: corners={corner_count}, reprojection={rms_px:.3f}px"
                )
            # Query TF at the image timestamp.  The RViz plugin uses Time(0),
            # which pairs the image with the newest robot pose and can create
            # centimetre-level errors while the arm is moving.  A buffered TF
            # lookup interpolates the robot pose to the actual exposure time.
            base_eef = self._lookup(self.args.base_frame, self.args.eef_frame, image_ns)
            if self.args.sensor_frame == self.optical_frame:
                sensor_optical = np.eye(4, dtype=np.float64)
            else:
                sensor_optical = self._lookup(self.args.sensor_frame, self.optical_frame, image_ns)
            sensor_target = sensor_optical @ optical_target
        except (ValueError, tf2_ros.TransformException, cv2.error, np.linalg.LinAlgError) as exc:
            self._throttled_warn(str(exc), msg.header.stamp)
            return

        if self._is_duplicate(base_eef):
            self._throttled_warn("robot pose is too close to an existing sample; move farther", msg.header.stamp)
            return

        if self.args.auto_capture or self.capture_requested:
            self._save_sample(
                image,
                image_ns,
                joints[0] if joints is not None else None,
                base_eef,
                sensor_target,
                corner_count,
                rms_px,
            )
            self.capture_requested = False
            self.last_capture_ns = image_ns

    def _throttled_warn(self, message: str, stamp: RosTime) -> None:
        current_ns = stamp_ns(stamp)
        if current_ns - self.last_log_ns > 2_000_000_000:
            self.get_logger().warn(message)
            self.last_log_ns = current_ns

    def _save_sample(
        self,
        image: np.ndarray,
        image_ns: int,
        joint_ns: Optional[int],
        base_eef: np.ndarray,
        sensor_target: np.ndarray,
        corner_count: int,
        rms_px: float,
    ) -> None:
        sample_id = len(self.samples) + 1
        image_path = self.image_dir / f"sample_{sample_id:03d}.png"
        if not cv2.imwrite(str(image_path), image):
            raise RuntimeError(f"unable to write {image_path}")

        sample = {
            "id": sample_id,
            "image": str(image_path),
            "effector_wrt_world": flatten_matrix(base_eef),
            "object_wrt_sensor": flatten_matrix(sensor_target),
            "image_stamp_ns": int(image_ns),
            "tf_lookup_stamp_ns": int(image_ns),
            "joint_stamp_ns": int(joint_ns) if joint_ns is not None else None,
            "joint_image_delta_ms": abs(image_ns - joint_ns) / 1e6 if joint_ns is not None else None,
            "charuco_corners": int(corner_count),
            "reprojection_error_px": float(rms_px),
        }
        self.samples.append(sample)
        self._write_dataset()
        delta_text = (
            "n/a"
            if sample["joint_image_delta_ms"] is None
            else f"{sample['joint_image_delta_ms']:.2f}"
        )
        self.get_logger().info(
            f"Saved sample {sample_id}/{len(self.samples)}: corners={corner_count} "
            f"reprojection={rms_px:.3f} px joint/image delta={delta_text} ms"
        )

    def _write_dataset(self) -> None:
        data = {
            "format": "thor7_handeye_charuco_v1",
            "mount": "eye_to_hand",
            "base_frame": self.args.base_frame,
            "eef_frame": self.args.eef_frame,
            "sensor_frame": self.args.sensor_frame,
            "optical_frame": self.optical_frame,
            "target_frame": "handeye_target",
            "board": {
                "dictionary": self.args.dictionary,
                "squares_x": self.args.squares_x,
                "squares_y": self.args.squares_y,
                "square_size_m": self.args.square_size,
                "marker_size_m": self.args.marker_size,
            },
            "camera_info_topic": self.args.camera_info_topic,
            "image_topic": self.args.image_topic,
            "joint_topic": self.args.joint_topic,
            "samples": self.samples,
        }
        self.output_path.parent.mkdir(parents=True, exist_ok=True)
        fd, temporary = tempfile.mkstemp(prefix=self.output_path.name + ".", dir=str(self.output_path.parent))
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as stream:
                yaml.safe_dump(data, stream, sort_keys=False)
            os.replace(temporary, self.output_path)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="handeye_samples.yaml")
    parser.add_argument("--image-dir", default=None)
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--image-topic", default="/camera/camera/color/image_raw")
    parser.add_argument("--camera-info-topic", default="/camera/camera/color/camera_info")
    parser.add_argument("--joint-topic", default="/joint_states")
    parser.add_argument("--trigger-service", default="/thor7_handeye/capture")
    parser.add_argument("--base-frame", default="base_link")
    parser.add_argument("--eef-frame", default="link6")
    parser.add_argument(
        "--sensor-frame",
        default="camera_color_optical_frame",
        help="frame for object_wrt_sensor; use the same optical frame as the grasp node",
    )
    parser.add_argument("--squares-x", type=int, default=11)
    parser.add_argument("--squares-y", type=int, default=8)
    parser.add_argument("--dictionary", default="DICT_4X4_250")
    parser.add_argument(
        "--square-size",
        type=float,
        required=True,
        help="measured printed square side in metres (for the current board: 0.025 if verified)",
    )
    parser.add_argument(
        "--marker-size",
        type=float,
        required=True,
        help="measured printed ArUco black marker side in metres",
    )
    parser.add_argument("--min-corners", type=int, default=20)
    parser.add_argument("--max-reprojection-px", type=float, default=1.5)
    parser.add_argument("--max-sync-ms", type=float, default=40.0)
    parser.add_argument("--tf-timeout", type=float, default=0.15)
    parser.add_argument(
        "--max-tf-lag-ms",
        type=float,
        default=5000.0,
        help="maximum allowed image-newer-than-TF lag for stopped-arm fallback (ms)",
    )
    parser.add_argument("--min-motion-m", type=float, default=0.005)
    parser.add_argument("--min-motion-deg", type=float, default=2.0)
    parser.add_argument("--auto-capture", action="store_true")
    parser.add_argument("--min-interval", type=float, default=2.0)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    rclpy.init()
    node = None
    try:
        node = HandeyeCollector(args)
        rclpy.spin(node)
    except (KeyboardInterrupt, ExternalShutdownException, RuntimeError, ValueError) as exc:
        if node is not None and not isinstance(exc, (KeyboardInterrupt, ExternalShutdownException)):
            node.get_logger().error(str(exc))
        elif node is None:
            print(str(exc), file=sys.stderr)
        return 1
    finally:
        if node is not None:
            node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
